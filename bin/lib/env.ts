export function parseEnv(text: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq > 0) out.set(t.slice(0, eq), t.slice(eq + 1));
  }
  return out;
}

export function isMissing(k: EnvKey, values: Map<string, string>): boolean {
  const v = values.get(k.key);
  return v === undefined || v === "" || k.placeholders.includes(v);
}

export function generateSecret(): string {
  return randomBytes(32).toString("base64url"); // 43 chars
}

export function serializeEnv(values: Map<string, string>): string {
  const order = ENV_SCHEMA.map((e) => e.key);
  const keys = [...values.keys()].sort((a, b) => {
    const ia = order.indexOf(a), ib = order.indexOf(b);
    return (ia === -1 ? order.length : ia) - (ib === -1 ? order.length : ib);
  });
  return keys.map((k) => `${k}=${values.get(k)}`).join("\n") + "\n";
}

export function renderEnvExample(): string {
  const lines: string[] = [];
  for (const e of ENV_SCHEMA) {
    if (e.comment) lines.push(`# ${e.comment}`);
    lines.push(e.commentedInExample ? `# ${e.key}=${e.example}` : `${e.key}=${e.example}`);
  }
  return lines.join("\n") + "\n";
}

// The `mode` option only applies when the file is created; chmod after the
// write keeps a pre-existing .env locked down to 0600 as well.
export function writeEnvFile(path: string, values: Map<string, string>): void {
  writeFileSync(path, serializeEnv(values), { mode: 0o600 });
  chmodSync(path, 0o600);
}
